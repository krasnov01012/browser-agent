"""Sub-агент-экстрактор — продвинутый паттерн №2.

Чтение длинной страницы стоит 3–10k токенов, и в основном контексте они
остались бы навсегда. Вместо этого текст уходит отдельному агенту на дешёвой
модели, а обратно возвращается только ответ на конкретный вопрос — обычно
100–300 токенов.

Основной контекст сырую страницу не видит никогда.
"""

from __future__ import annotations

import logging

from ..llm import LLMError, LLMRouter, Message

log = logging.getLogger(__name__)

MAX_ANSWER_TOKENS = 700

SYSTEM = """Ты извлекаешь информацию из текста веб-страницы.

Тебе дают содержимое страницы и вопрос. Ответь на вопрос, опираясь ТОЛЬКО
на этот текст.

Правила:
- Отвечай кратко и по делу, без вступлений и пересказа всей страницы.
- Если в тексте есть конкретные значения (числа, даты, названия, суммы) —
  приводи их дословно.
- Если ответа в тексте нет, так и напиши: «в тексте этого нет». Не додумывай.
- Если просят список — давай список, по одному пункту на строку.
- Не давай советов о том, что делать дальше. Твоя работа — только факты."""


async def extract(
    router: LLMRouter,
    *,
    content: str,
    question: str,
    detailed: bool = False,
) -> str:
    """Задаёт вопрос к тексту страницы на дешёвой модели."""
    if not content.strip():
        return "Страница не содержит читаемого текста."

    budget = MAX_ANSWER_TOKENS * (2 if detailed else 1)
    prompt = (
        f"Вопрос: {question}\n\n--- Содержимое страницы ---\n{content}\n--- Конец содержимого ---"
    )

    try:
        response = await router.call(
            "extractor",
            [Message.system(SYSTEM), Message.user(prompt)],
            max_tokens=budget,
        )
    except LLMError as e:
        log.warning("экстрактор не ответил: %s", e)
        # Не роняем задачу: отдаём начало текста, пусть агент решает сам.
        head = content[:1500]
        return f"(экстрактор недоступен: {e}). Начало страницы:\n{head}"

    answer = response.message.content.strip()
    return answer or "Экстрактор не нашёл ответа в тексте страницы."
