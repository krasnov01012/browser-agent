"""Реестр совершённых действий.

История компактится: у шага старше трёх последних остаётся однострочное
резюме, а через десяток шагов агент уже не может ответить на вопрос «сколько
раз я это сделал». Для обратимых действий это неважно, для необратимых решает
исход: в прогоне `vacancy_apply` агент отправил четыре отклика вместо трёх
и в итоговом отчёте написал, что не отправил ни одного (docs/DECISIONS.md ADR-039).

Реестр живёт вне истории и собирается заново на каждом шаге — поэтому
компакция до него не достаёт, как и до scratchpad. В отличие от scratchpad,
сюда пишет не модель, а цикл: то, что действительно произошло, не должно
зависеть от того, догадался ли агент это записать.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field

#: сколько разных действий показывать
#:
#: Показываются самые частые, а не самые свежие: реестр отвечает на вопрос
#: «сколько раз», и повторы важнее одиночных кликов по полям ввода.
MAX_LINES = 8


@dataclass
class Ledger:
    """Что агент уже сделал за прогон, по подписям элементов."""

    done: Counter[str] = field(default_factory=Counter)

    def add(self, label: str) -> None:
        text = label.strip()
        if text:
            self.done[text] += 1

    def __len__(self) -> int:
        return sum(self.done.values())

    def notice(self) -> str:
        """Строка для контекста. Пусто — пока ничего не сделано."""
        if not self.done:
            return ""

        top = self.done.most_common(MAX_LINES)
        rows = "; ".join(f"«{label}» ×{count}" for label, count in top)
        hidden = len(self.done) - len(top)
        if hidden:
            rows += f"; и ещё {hidden} других"

        return (
            f"УЖЕ СДЕЛАНО за этот прогон: {rows}. "
            f"Это перечень действий, которые состоялись на самом деле, — он не "
            f"зависит от того, что вы помните о предыдущих шагах. Если в задаче "
            f"названо количество, считайте по нему. Действие, которого здесь "
            f"нужное число, повторять не надо: заканчивайте задачу."
        )
