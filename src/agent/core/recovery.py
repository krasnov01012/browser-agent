"""Восстановление после неудачных действий — продвинутый паттерн №1.

Реализуется первым, потому что без него агент не работает: браузерные агенты
отказывают в основном не потому, что выбрали не тот элемент, а потому, что
упёрлись и продолжают долбить одно и то же.

Здесь два механизма: детектор зацикливания и подсказки по классам ошибок.
Сами сообщения об ошибках живут в tools/errors.py — они уже написаны так,
чтобы указывать направление.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field

#: сколько повторов одного действия внутри окна считается зацикливанием
LOOP_THRESHOLD = 3
#: в скольких последних шагах их искать
#:
#: Окно из шести шагов ловило карусель из трёх («клик → перекрыт → Escape →
#: тот же клик»), но не более длинную. В прогоне `vacancies` агент открывал
#: одну и ту же панель на шагах 5, 8, 12 и 23, между ними успевая потыкать
#: в её содержимое: три повтора в шесть шагов не укладывались ни разу,
#: и детектор промолчал все двадцать (docs/ADR.md ADR-032).
LOOP_WINDOW = 10
#: сколько ошибок подряд означает, что пора менять подход целиком
ERROR_STREAK_THRESHOLD = 4
#: сколько раз можно наткнуться на перекрытие, прежде чем это станет системой
BLOCKED_THRESHOLD = 3
#: сколько безрезультатных вызовов одного инструмента в окне — уже перебор
#:
#: Счёт по точной подписи ловит только буквальные повторы. В прогоне с Gmail
#: агент семь раз подряд вызвал find_in_page, меняя регистр и язык запроса:
#: подписи все разные, порог повторов не брался ни разу, и детектор молчал
#: до девятого шага (docs/ADR.md ADR-039).
#:
#: Считаются только вызовы, ничего на странице не изменившие. Без этого условия
#: детектор ругался бы на десять кликов подряд по разным кнопкам — а это не
#: буксование, а обычная работа.
SAME_TOOL_THRESHOLD = 4
#: сколько шагов подряд с неизменным состоянием страницы — уже не совпадение
#:
#: Самый дешёвый сигнал буксования из всех: если после действия страница
#: та же самая, действие ничего не дало. Три подряд — это уже не задержка
#: отрисовки, а тупик.
STALE_STATE_THRESHOLD = 3


def signature(name: str, arguments: dict) -> str:
    return f"{name}:{json.dumps(arguments, sort_keys=True, ensure_ascii=False)}"


def plural(count: int, one: str, few: str, many: str) -> str:
    """«1 шаг», «3 шага», «7 шагов». Подсказки читает модель — пусть читаются."""
    if count % 100 // 10 == 1:
        return many
    last = count % 10
    if last == 1:
        return one
    if 2 <= last <= 4:
        return few
    return many


@dataclass
class Recovery:
    """Следит за динамикой шагов и вмешивается, когда агент буксует."""

    recent: list[str] = field(default_factory=list)
    #: имена инструментов по шагам; пустая строка — шаг что-то изменил
    tools: list[str] = field(default_factory=list)
    error_streak: int = 0
    blocked: int = 0
    #: подпись действия -> на скольких повторах о ней предупреждали в прошлый раз
    _nudged_for: dict[str, int] = field(default_factory=dict)
    _nudged_blocked: bool = False
    #: имя инструмента -> на скольких вызовах о нём предупреждали
    _nudged_tool: dict[str, int] = field(default_factory=dict)
    #: отпечаток последнего состояния страницы и сколько шагов он держится
    _state_key: str = ""
    _state_repeats: int = 0
    _nudged_stale: int = 0

    def observe(
        self,
        name: str,
        arguments: dict,
        *,
        failed: bool,
        kind: str = "",
        state_key: str = "",
        changed: bool = True,
    ) -> None:
        self.recent.append(signature(name, arguments))
        del self.recent[:-LOOP_WINDOW]
        # Шаг, который что-то изменил, занимает место в окне, но в счёт перебора
        # не идёт: перебирают формулировки там, где ничего не происходит.
        self.tools.append("" if changed else name)
        del self.tools[:-LOOP_WINDOW]
        self.error_streak = self.error_streak + 1 if failed else 0
        if kind == "covered":
            self.blocked += 1
        if state_key:
            if state_key == self._state_key:
                self._state_repeats += 1
            else:
                self._state_key = state_key
                self._state_repeats = 0
                self._nudged_stale = 0

    # ── подсказки, вставляемые в контекст перед следующим шагом ──────

    def notice(self) -> str:
        """Что сказать агенту перед очередным шагом. Пусто — если всё идёт."""
        parts = [
            self._loop_notice(),
            self._same_tool_notice(),
            self._stale_notice(),
            self._blocked_notice(),
            self._streak_notice(),
        ]
        return "\n\n".join(p for p in parts if p)

    def _loop_notice(self) -> str:
        """Действие повторяется внутри окна — подряд или через другие шаги.

        Считать только подряд идущие одинаковые действия недостаточно: самый
        дорогой вид зацикливания — чередование. В прогоне `vacancies` агент
        19 шагов крутил цикл «клик по фильтру → он перекрыт → Escape → клик
        по тому же фильтру»: три подряд одинаковых действия там не встречались
        ни разу, детектор молчал (docs/ADR.md ADR-025).
        """
        current = self.recent[-1] if self.recent else ""
        repeats = self.recent.count(current)
        if repeats < LOOP_THRESHOLD:
            return ""
        # Сказать один раз за прогон — значит замолчать навсегда именно тогда,
        # когда подсказку проигнорировали. В прогоне `vacancies` детектор
        # отработал на третьем `scroll down` и умолк; агент открутил ещё
        # девять таких же шагов до конца бюджета, и больше его никто
        # не окликнул. Повторяем на каждом новом пороге повторов — на третьем,
        # шестом, девятом (docs/ADR.md ADR-034).
        if repeats < self._nudged_for.get(current, 0) + LOOP_THRESHOLD:
            return ""
        self._nudged_for[current] = repeats

        steps = plural(len(self.recent), "шаг", "шага", "шагов")
        times = plural(repeats, "раз", "раза", "раз")
        return (
            f"ВНИМАНИЕ: за последние {len(self.recent)} {steps} вы повторили одно "
            f"и то же действие {repeats} {times}, и к цели это не приблизило. Если "
            f"между повторами вы делали что-то ещё — значит, вы ходите по кругу: "
            f"второе действие отменяет первое. Повторять цикл бессмысленно. "
            f"Разберитесь, что мешает: элемент может быть перекрыт тем, что вы "
            f"сами только что открыли, находиться в другой вкладке или требовать "
            f"предварительного шага. Выберите другой путь к цели."
        )

    def _same_tool_notice(self) -> str:
        """Один инструмент вызывается снова и снова, меняются только аргументы.

        Перебор формулировок ощущается работой, но подходом не является:
        инструмент уже ответил, что искомого нет, и следующий синоним получит
        тот же ответ. Ловится отдельно от повторов, потому что по подписи
        такие вызовы все разные (docs/ADR.md ADR-039).
        """
        current = self.tools[-1] if self.tools else ""
        if not current:
            # Последний шаг что-то изменил — говорить о буксовании не о чем.
            return ""
        if self.recent and self.recent.count(self.recent[-1]) >= LOOP_THRESHOLD:
            # Буквальный повтор разбирает детектор циклов. Два абзаца подряд
            # об одной и той же беде обесценивают оба.
            return ""

        calls = self.tools.count(current)
        if calls < SAME_TOOL_THRESHOLD:
            return ""
        if calls < self._nudged_tool.get(current, 0) + SAME_TOOL_THRESHOLD:
            return ""
        self._nudged_tool[current] = calls

        steps = plural(len(self.tools), "шаг", "шага", "шагов")
        times = plural(calls, "раз", "раза", "раз")
        return (
            f"ВНИМАНИЕ: за последние {len(self.tools)} {steps} вы {calls} {times} "
            f"вызвали {current}, меняя только аргументы, и страница от этого "
            f"ни разу не изменилась. Перебор формулировок — это не смена подхода: "
            f"инструмент отвечает про ту же самую страницу и ответит так же. "
            f"Возьмите другой инструмент или другой путь к цели."
        )

    def _stale_notice(self) -> str:
        """Страница не меняется, что бы агент ни делал.

        Самый общий признак тупика: если после действия состояние то же самое,
        действие не сработало — независимо от того, что вернул инструмент.
        """
        if self._state_repeats < STALE_STATE_THRESHOLD:
            return ""
        if self._state_repeats < self._nudged_stale + STALE_STATE_THRESHOLD:
            return ""
        self._nudged_stale = self._state_repeats

        steps = plural(self._state_repeats, "шаг", "шага", "шагов")
        return (
            f"ВНИМАНИЕ: состояние страницы не меняется уже {self._state_repeats} "
            f"{steps} подряд — ваши действия к ней ничего не добавляют. Либо вы "
            f"обращаетесь не к той области, либо нужного на этой странице нет. "
            f"Посмотрите список элементов целиком и выберите ход, который "
            f"действительно меняет страницу: раскройте свёрнутое, перейдите "
            f"в другой раздел, откройте адрес напрямую. Если продвинуться "
            f"не получается — спросите пользователя через ask_user."
        )

    def _blocked_notice(self) -> str:
        """Перекрытия перестали быть случайностью.

        Одно перекрытие — обычное дело: баннер, подсказка, куки. Три за прогон
        означают другое: агент сам открывает блок, который сам себе и мешает,
        и не связывает одно с другим. В прогоне `vacancies` так ушло двадцать
        шагов на панель настроек поверх страницы, где искомое уже было видно
        (docs/ADR.md ADR-032).
        """
        if self.blocked < BLOCKED_THRESHOLD or self._nudged_blocked:
            return ""
        self._nudged_blocked = True

        times = plural(self.blocked, "раз", "раза", "раз")
        return (
            f"ВНИМАНИЕ: вы уже {self.blocked} {times} наткнулись на перекрытие. "
            f"Скорее всего, вы сами открываете блок, который сам же вам и мешает: "
            f"панель настроек, форму, всплывающее окно. Закройте его и работайте "
            f"с тем, что на странице уже есть. Донастройка — не обязательная часть "
            f"задачи: если нужное вам уже видно, читайте и отбирайте сами, "
            f"а не добивайтесь этого через интерфейс сайта."
        )

    def _streak_notice(self) -> str:
        if self.error_streak < ERROR_STREAK_THRESHOLD:
            return ""
        return (
            f"ВНИМАНИЕ: подряд идёт {self.error_streak} неудачных действий. "
            f"Остановитесь и посмотрите на состояние страницы целиком — возможно, "
            f"вы работаете не с той областью или страница ушла в другое состояние, "
            f"чем вы предполагаете. Если продвинуться не получается, спросите "
            f"пользователя через ask_user."
        )


def budget_notice(exhaustion: float, steps_left: int) -> str:
    """Предупреждение о подходящем к концу бюджете."""
    if exhaustion < 0.8:
        return ""
    return (
        f"БЮДЖЕТ: осталось примерно {steps_left} шагов. Начинайте сворачиваться: "
        f"доделайте то, что можно, и вызовите finish с честным отчётом о том, "
        f"что успели, а что нет."
    )


NO_TOOL_CALL_NOTICE = (
    "Вы ответили текстом, но не вызвали инструмент. Каждый шаг должен быть ровно "
    "одним вызовом инструмента. Если задача выполнена — вызовите finish. Если "
    "нужны данные от пользователя — ask_user."
)
